export default function StreamingLinks({ links, className = "" }: Props) {
  const entries = Object.entries(links).filter(([, url]) => !!url) as [
    keyof SocialLinks,
    string
  ][];

  if (entries.length === 0) return null;

  return (
    <div className={`flex flex-wrap gap-3 ${className}`}>
      {entries.map(([platform, url]) => {
        const icon = icons[platform];
        if (!icon) return null;
        return (
          <a
            key={platform}
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            aria-label={icon.label}
            className="flex items-center gap-2 px-3 py-2 border border-border text-muted hover:text-white hover:border-white transition-colors duration-200 text-xs uppercase tracking-widest"
          >
            <svg
              viewBox="0 0 24 24"
              className="w-4 h-4 fill-current"
              aria-hidden="true"
            >
              <path d={icon.path} />
            </svg>
            <span>{icon.label}</span>
          </a>
        );
      })}
    </div>
  );
}
